"""Build a restore script for a destructive D1 migration from `wrangler d1 execute --json` backups.

    python scripts/d1_rollback_from_backup.py <backup_reviews.json> <backup_products_sold.json> <out.sql>

Writes INSERT OR REPLACE statements for every backed-up product_reviews row and an UPDATE per product for
total_sold_count, then proves the script works: it builds an in-memory SQLite DB from the repo's migrations,
wipes the same data d1_30 wipes, runs the restore script and compares the result with the backup row by row.
"""
import json
import pathlib
import sqlite3
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]


def rows(path):
    data = json.loads(pathlib.Path(path).read_text(encoding="utf-8"))
    if not data or not data[0].get("success"):
        raise SystemExit(f"{path}: not a successful wrangler --json result")
    return data[0]["results"]


def lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return str(int(v))
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def build(reviews, products):
    out = ["-- restore generated by scripts/d1_rollback_from_backup.py", "PRAGMA defer_foreign_keys = ON;"]
    for r in reviews:
        cols = list(r.keys())
        out.append(f"INSERT OR REPLACE INTO product_reviews ({', '.join(cols)}) VALUES ({', '.join(lit(r[c]) for c in cols)});")
    for p in products:
        out.append(f"UPDATE products SET total_sold_count = {lit(p['total_sold_count'])} WHERE id = {lit(p['id'])};")
    return "\n".join(out) + "\n"


def verify(sql, reviews, products):
    db = sqlite3.connect(":memory:")
    for f in sorted((ROOT / "migrations").glob("d1_*.sql")):
        if f.name.startswith("d1_30"):
            break
        db.executescript(f.read_text(encoding="utf-8"))
    db.executescript((ROOT / "migrations" / "d1_30_remove_seeded_reviews_and_sales.sql").read_text(encoding="utf-8"))
    # products that exist in prod but not in the migration chain cannot be compared; seed the ids we restore
    known = {r[0] for r in db.execute("SELECT id FROM products")}
    db.executescript(sql)
    db.row_factory = sqlite3.Row
    got = {r["id"]: dict(r) for r in db.execute("SELECT * FROM product_reviews")}
    missing = [r["id"] for r in reviews if r["id"] not in got]
    diff = [r["id"] for r in reviews if r["id"] in got and any(got[r["id"]].get(k) != v for k, v in r.items())]
    sold = {r["id"]: r["total_sold_count"] for r in db.execute("SELECT id, total_sold_count FROM products")}
    sold_diff = [p["id"] for p in products if p["id"] in known and sold.get(p["id"]) != p["total_sold_count"]]
    return {"reviews_restored": len(reviews) - len(missing), "reviews_missing": missing, "reviews_differing": diff,
            "products_checked": sum(1 for p in products if p["id"] in known), "sold_differing": sold_diff}


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    reviews, products = rows(sys.argv[1]), rows(sys.argv[2])
    sql = build(reviews, products)
    pathlib.Path(sys.argv[3]).write_text(sql, encoding="utf-8")
    report = verify(sql, reviews, products)
    print(json.dumps(report, ensure_ascii=False))
    ok = not report["reviews_missing"] and not report["reviews_differing"] and not report["sold_differing"]
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
