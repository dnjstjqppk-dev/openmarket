"""Rehearse migrations/d1_31 on a copy of the production rows and build its rollback.

    python scripts/d1_31_rehearse_on_backup.py <backup_dir> <rollback.sql>

<backup_dir> (keep it under the git-ignored .ops-backups/: the rows include personal data) holds `wrangler d1 execute --json` exports named backup_<table>.json (orders, sub_orders, settlements,
order_items, inventory_ledger, product_skus, products, payment_transactions). The script
  1. builds the schema from every d1_*.sql migration in an in-memory SQLite, loads the exported rows,
  2. runs d1_31 and prints exactly what it changes (the expected production result),
  3. writes a rollback (UPDATEs back to the exported values + DELETE of the rows d1_31 inserts),
  4. runs the rollback and proves every exported row is back byte for byte and the inserted rows are gone,
  5. runs d1_31 twice on a fresh copy to prove the second run changes nothing.
Exit code 0 only if all checks hold.
"""
import json
import pathlib
import sqlite3
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
MIG = ROOT / "migrations"
D1_31 = (MIG / "d1_31_void_unpaid_orders_marked_paid.sql").read_text(encoding="utf-8")
TABLES = ["products", "product_skus", "orders", "sub_orders", "order_items", "settlements", "inventory_ledger", "payment_transactions"]
CHANGED = {"orders": "id", "sub_orders": "id", "settlements": "id", "product_skus": "id", "products": "id"}
INSERTED = {"inventory_ledger": "ldg_d1_31_%", "admin_audit_log": "aud_d1_31_%"}


def load(backup_dir):
    data = {}
    for t in TABLES:
        j = json.loads((backup_dir / f"backup_{t}.json").read_text(encoding="utf-8"))
        if not j[0].get("success"):
            raise SystemExit(f"backup_{t}.json is not a successful export")
        data[t] = j[0]["results"]
    return data


def fresh_db(data):
    db = sqlite3.connect(":memory:")
    for f in sorted(MIG.glob("d1_*.sql")):
        if f.name.startswith("d1_31"):
            break
        db.executescript(f.read_text(encoding="utf-8"))
    for t in TABLES:  # drop seed rows: the copy must contain production rows only
        db.execute(f"DELETE FROM {t}")
    db.execute("DELETE FROM admin_audit_log")
    for t in TABLES:
        for r in data[t]:
            cols = list(r)
            db.execute(f"INSERT INTO {t} ({', '.join(cols)}) VALUES ({', '.join('?' * len(cols))})", [r[c] for c in cols])
    db.commit()
    return db


def snapshot(db, table, key="id"):
    db.row_factory = sqlite3.Row
    out = {r[key]: dict(r) for r in db.execute(f"SELECT * FROM {table}")}
    db.row_factory = None
    return out


def lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    backup_dir, out_sql = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    data = load(backup_dir)

    db = fresh_db(data)
    before = {t: snapshot(db, t) for t in CHANGED}
    db.executescript(D1_31)
    after = {t: snapshot(db, t) for t in CHANGED}

    # State-machine triggers (e.g. trg_orders_payment_transition) forbid CANCELLED -> PAID by design, so the emergency
    # rollback drops the triggers of the restored tables and recreates them from their exact schema definition.
    triggers = db.execute("SELECT name, sql FROM sqlite_master WHERE type = 'trigger' AND tbl_name IN (%s) ORDER BY name"
                          % ",".join(lit(t) for t in list(CHANGED) + list(INSERTED))).fetchall()
    changes, rollback = {}, ["-- rollback for migrations/d1_31, generated by scripts/d1_31_rehearse_on_backup.py",
                             "-- triggers on the restored tables are dropped for the restore and recreated unchanged at the end"]
    rollback += [f"DROP TRIGGER IF EXISTS {name};" for name, _ in triggers]
    for t, key in CHANGED.items():
        changed_ids = [k for k in before[t] if before[t][k] != after[t].get(k)]
        changes[t] = len(changed_ids)
        for k in changed_ids:
            cols = [c for c in before[t][k] if before[t][k][c] != after[t][k][c]]
            rollback.append(f"UPDATE {t} SET {', '.join(f'{c} = {lit(before[t][k][c])}' for c in cols)} WHERE {key} = {lit(k)};")
    for t, pattern in INSERTED.items():
        changes[f"{t}_inserted"] = db.execute(f"SELECT COUNT(*) FROM {t} WHERE id LIKE ?", (pattern,)).fetchone()[0]
        rollback.append(f"DELETE FROM {t} WHERE id LIKE {lit(pattern)};")
    rollback += [sql.rstrip(";") + ";" for _, sql in triggers]
    out_sql.write_text("\n".join(rollback) + "\n", encoding="utf-8")

    expected = {
        "orders_cancelled": db.execute("SELECT COUNT(*) FROM orders WHERE payment_status = 'CANCELLED' AND id IN (%s)" % ",".join(lit(r["id"]) for r in data["orders"])).fetchone()[0],
        "settlements_cancelled": db.execute("SELECT COUNT(*) FROM settlements WHERE status = 'CANCELLED'").fetchone()[0],
        "units_restocked": db.execute("SELECT COALESCE(SUM(quantity_delta), 0) FROM inventory_ledger WHERE id LIKE 'ldg_d1_31_%'").fetchone()[0],
        "sold_total_after": db.execute("SELECT SUM(total_sold_count) FROM products").fetchone()[0],
        "remaining_paid_without_payment": db.execute("SELECT COUNT(*) FROM orders WHERE payment_status = 'PAID' AND paid_at IS NULL").fetchone()[0],
    }

    db.executescript("\n".join(rollback))
    restored = {t: snapshot(db, t) for t in CHANGED}
    triggers_after = db.execute("SELECT name, sql FROM sqlite_master WHERE type = 'trigger' AND tbl_name IN (%s) ORDER BY name"
                                % ",".join(lit(t) for t in list(CHANGED) + list(INSERTED))).fetchall()
    rollback_ok = all(restored[t] == before[t] for t in CHANGED) and triggers_after == triggers and all(
        db.execute(f"SELECT COUNT(*) FROM {t} WHERE id LIKE ?", (p,)).fetchone()[0] == 0 for t, p in INSERTED.items())

    db2 = fresh_db(data)
    db2.executescript(D1_31)
    first = {t: snapshot(db2, t) for t in list(CHANGED) + ["inventory_ledger", "admin_audit_log"]}
    db2.executescript(D1_31)
    second = {t: snapshot(db2, t) for t in list(CHANGED) + ["inventory_ledger", "admin_audit_log"]}
    idempotent = first == second

    print(json.dumps({"changes": changes, "expected": expected, "rollback_restores_exactly": rollback_ok,
                      "second_run_is_noop": idempotent, "rollback_lines": len(rollback)}, ensure_ascii=False, indent=1))
    sys.exit(0 if rollback_ok and idempotent and expected["remaining_paid_without_payment"] == 0 else 1)


if __name__ == "__main__":
    main()
