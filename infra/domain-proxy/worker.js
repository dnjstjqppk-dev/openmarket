// infra/domain-proxy/worker.js — worker `olmoa-edge` in the DOMAIN account.
//
// The olmoa.com zone lives in the operator's domain account, while the app workers
// (storefront/admin/partner/api), D1, R2 and secrets live in the workers account.
// Worker Custom Domains only bind a zone to a worker in the same account, so this
// worker owns the custom domains and forwards each host to its workers.dev upstream.
//
// - olmoa.com           -> openmarket (apex storefront); crawl paths go straight to the API
// - admin./partner.     -> olmoa-admin / olmoa-partner (static consoles)
// - www.olmoa.com       -> 301 https://olmoa.com (path + query kept)
// - api.olmoa.com is deliberately NOT proxied: a proxy hop would make every browser
//   share this worker's egress IP, collapsing the API's per-IP rate limits (login
//   5/min). Browsers keep calling the API's workers.dev host (VITE_API_BASE_URL).

export const UPSTREAMS = {
  'olmoa.com': 'https://openmarket.dnjstjqppk.workers.dev',
  'admin.olmoa.com': 'https://olmoa-admin.dnjstjqppk.workers.dev',
  'partner.olmoa.com': 'https://olmoa-partner.dnjstjqppk.workers.dev'
};
export const API_UPSTREAM = 'https://olmoa-api.dnjstjqppk.workers.dev';
export const APEX = 'olmoa.com';

// Same list as apps/storefront/edge/apex-worker.js CRAWL_PATHS (D1-generated by the API).
const CRAWL_EXACT = new Set(['/robots.txt', '/sitemap.xml', '/sitemap-index.xml', '/llms.txt', '/llms-full.txt']);
export function isCrawlPath(pathname) {
  return CRAWL_EXACT.has(pathname) || pathname.startsWith('/sitemaps/');
}

const HSTS = 'max-age=31536000; includeSubDomains'; // no preload until the domain has run stably

// Hop-by-hop / edge-set request headers that must not be replayed upstream.
const DROP_REQ = ['host', 'cf-connecting-ip', 'cf-ipcountry', 'cf-ray', 'cf-visitor', 'x-forwarded-proto', 'x-real-ip'];

export function upstreamFor(url) {
  const host = url.hostname.toLowerCase();
  if (host === APEX && isCrawlPath(url.pathname)) return API_UPSTREAM;
  return UPSTREAMS[host] || null;
}

export default {
  async fetch(request) {
    const url = new URL(request.url);
    const host = url.hostname.toLowerCase();

    if (url.protocol === 'http:' || host === `www.${APEX}`) {
      const target = host === `www.${APEX}` ? APEX : host;
      return new Response(null, {
        status: 301,
        headers: { Location: `https://${target}${url.pathname}${url.search}`, 'Strict-Transport-Security': HSTS }
      });
    }

    const upstream = upstreamFor(url);
    if (!upstream) return new Response('Not Found', { status: 404, headers: { 'Content-Type': 'text/plain' } });

    const upstreamUrl = new URL(url.pathname + url.search, upstream);
    const headers = new Headers(request.headers);
    for (const h of DROP_REQ) headers.delete(h);
    const init = { method: request.method, headers, redirect: 'manual' };
    if (request.method !== 'GET' && request.method !== 'HEAD') init.body = request.body;

    const res = await fetch(upstreamUrl.toString(), init);
    const out = new Headers(res.headers);
    out.set('Strict-Transport-Security', HSTS);
    // Keep the visitor on the custom domain if an upstream redirects to its own host.
    const loc = out.get('Location');
    if (loc && loc.startsWith(upstream)) out.set('Location', `https://${host}${loc.slice(upstream.length)}`);
    return new Response(res.body, { status: res.status, statusText: res.statusText, headers: out });
  }
};
