// apps/cloudflare-gateway/src/routes/social-auth.js
// Kakao OAuth 2.0 login (authorization-code flow), fail-closed without credentials.
//   GET  /api/v1/auth/social/kakao/start[?state=...] -> 302 to Kakao authorize (501 JSON when unconfigured)
//   GET  /api/v1/auth/social/kakao/callback          -> 302 to the storefront login page:
//          success: /login?social_code=<one-time>&state=...   failure: /login?social_error=<CODE>&state=...
//   POST /api/v1/auth/social/kakao/exchange {code}   -> { token, user } (single use, 5 minutes)
// The JWT is never placed in a URL (URLs land in history, logs, and referers); the SPA
// exchanges the one-time code for it over POST. `state` is generated by the SPA, round-trips
// through the provider untouched, and is verified by the SPA (login CSRF protection).
// The account is found by (oauth_provider, oauth_subject) or created as ROLE_CUSTOMER.
// An e-mail already registered with a password is NEVER auto-linked (account takeover):
// the buyer signs in with the password instead (EMAIL_TAKEN).

import { issueToken } from '../lib/auth.js';
import { json, readJson, bad, str } from '../lib/http.js';
import { newId } from '../lib/ids.js';
import { randomToken, sha256Hex } from '../utils/crypto-auth.js';
import { storefrontBaseUrl } from '../lib/email.js';
import { publicUser } from './auth.js';

const AUTHORIZE_URL = 'https://kauth.kakao.com/oauth/authorize';
const TOKEN_URL = 'https://kauth.kakao.com/oauth/token';
const USERINFO_URL = 'https://kapi.kakao.com/v2/user/me';
const LOGIN_CODE_TTL_MS = 5 * 60 * 1000;
const STATE_RE = /^[A-Za-z0-9_-]{8,256}$/;

function kakaoConfig(env) {
  const key = env.KAKAO_REST_API_KEY;
  const redirect = env.KAKAO_REDIRECT_URI;
  if (!key || !redirect) return null;
  return { key, redirect, secret: env.KAKAO_CLIENT_SECRET || null };
}

function backToLogin(env, params) {
  const q = new URLSearchParams(params).toString();
  return Response.redirect(`${storefrontBaseUrl(env)}/login?${q}`, 302);
}

/** A state we echo must be one we could have sent: bounded, URL-safe, no markup. */
function echoableState(value) {
  const s = (value || '').trim();
  return STATE_RE.test(s) ? s : null;
}

export async function handleSocialAuthRoutes(request, url, env, corsHeaders) {
  if (!url.pathname.startsWith('/api/v1/auth/social/')) return null;
  const p = url.pathname;

  if (p === '/api/v1/auth/social/kakao/start' && request.method === 'GET') {
    const c = kakaoConfig(env);
    if (!c) return json(corsHeaders, { success: false, code: 'SOCIAL_LOGIN_NOT_INTEGRATED', error: '소셜 로그인은 아직 제공되지 않습니다.' }, 501);
    const rawState = url.searchParams.get('state');
    if (rawState !== null && !STATE_RE.test(rawState.trim())) {
      throw bad('INVALID_STATE', '유효하지 않은 로그인 요청 식별자입니다.');
    }
    // account_email scope is required: without an e-mail no account can be created (see below).
    const params = { client_id: c.key, redirect_uri: c.redirect, response_type: 'code', scope: 'account_email' };
    if (rawState) params.state = rawState.trim();
    const authorize = `${AUTHORIZE_URL}?${new URLSearchParams(params)}`;
    return Response.redirect(authorize, 302);
  }

  if (p === '/api/v1/auth/social/kakao/callback' && request.method === 'GET') {
    const c = kakaoConfig(env);
    if (!c) return json(corsHeaders, { success: false, code: 'SOCIAL_LOGIN_NOT_INTEGRATED', error: '소셜 로그인은 아직 제공되지 않습니다.' }, 501);
    const state = echoableState(url.searchParams.get('state'));
    const withState = (params) => (state ? { ...params, state } : params);
    const code = (url.searchParams.get('code') || '').trim();
    if (!code) return backToLogin(env, withState({ social_error: 'OAUTH_DENIED' }));
    try {
      // 1. authorization code -> access token (server to server; the code is never trusted by itself)
      const form = new URLSearchParams({ grant_type: 'authorization_code', client_id: c.key, redirect_uri: c.redirect, code });
      if (c.secret) form.set('client_secret', c.secret);
      const tokenRes = await fetch(TOKEN_URL, {
        method: 'POST',
        headers: { 'Content-Type': 'application/x-www-form-urlencoded;charset=utf-8' },
        body: form
      });
      if (!tokenRes.ok) return backToLogin(env, withState({ social_error: 'OAUTH_EXCHANGE_FAILED' }));
      const granted = await tokenRes.json();
      if (!granted || !granted.access_token) return backToLogin(env, withState({ social_error: 'OAUTH_EXCHANGE_FAILED' }));
      // 2. access token -> verified profile
      const meRes = await fetch(USERINFO_URL, { headers: { Authorization: `Bearer ${granted.access_token}` } });
      if (!meRes.ok) return backToLogin(env, withState({ social_error: 'OAUTH_PROFILE_FAILED' }));
      const profile = await meRes.json();
      const subject = String((profile && profile.id) || '');
      const account = (profile && profile.kakao_account) || {};
      const email = typeof account.email === 'string' ? account.email.toLowerCase() : '';
      const nickname = (profile.properties && profile.properties.nickname) || '';
      if (!subject) return backToLogin(env, withState({ social_error: 'OAUTH_PROFILE_FAILED' }));
      if (!email) return backToLogin(env, withState({ social_error: 'OAUTH_EMAIL_REQUIRED' }));
      // 3. find-or-create (never auto-link a password account)
      const linked = await env.DB.prepare("SELECT * FROM users WHERE oauth_provider = 'kakao' AND oauth_subject = ?").bind(subject).first();
      let user = linked;
      if (!user) {
        const taken = await env.DB.prepare('SELECT id FROM users WHERE LOWER(email) = ?').bind(email).first();
        if (taken) return backToLogin(env, withState({ social_error: 'EMAIL_TAKEN' }));
        const id = newId('usr');
        await env.DB.prepare(
          `INSERT INTO users (id, email, password_hash, full_name, phone, role, is_active, email_verified, oauth_provider, oauth_subject)
           VALUES (?, ?, ?, ?, '', 'ROLE_CUSTOMER', 1, ?, 'kakao', ?)`
        ).bind(id, email, `oauth:${randomToken(16)}`, String(nickname || '카카오 회원').slice(0, 50), account.is_email_verified === true ? 1 : 0, subject).run();
        user = await env.DB.prepare('SELECT * FROM users WHERE id = ?').bind(id).first();
      }
      if (Number(user.is_active) !== 1) return backToLogin(env, withState({ social_error: 'ACCOUNT_DISABLED' }));
      // 4. one-time login code (sha256 at rest). The SPA exchanges it for the JWT over POST;
      // the JWT itself never travels in a URL.
      const loginCode = randomToken(32);
      await env.DB.prepare('INSERT INTO social_login_codes (id, user_id, code_hash, expires_at) VALUES (?, ?, ?, ?)')
        .bind(newId('slc'), user.id, await sha256Hex(loginCode), new Date(Date.now() + LOGIN_CODE_TTL_MS).toISOString()).run();
      return backToLogin(env, withState({ social_code: loginCode }));
    } catch {
      return backToLogin(env, withState({ social_error: 'OAUTH_PROVIDER_ERROR' }));
    }
  }

  if (p === '/api/v1/auth/social/kakao/exchange' && request.method === 'POST') {
    const b = await readJson(request);
    const code = str(b.code, { field: '로그인 코드', max: 200, required: true });
    const invalid = () => bad('INVALID_LOGIN_CODE', '유효하지 않거나 만료된 로그인 코드입니다.');
    const row = await env.DB.prepare('SELECT * FROM social_login_codes WHERE code_hash = ? AND used_at IS NULL')
      .bind(await sha256Hex(code)).first();
    if (!row || new Date(row.expires_at).getTime() < Date.now()) throw invalid();
    // Mark used first: a concurrent replay loses this race and gets the same answer.
    const marked = await env.DB.prepare('UPDATE social_login_codes SET used_at = CURRENT_TIMESTAMP WHERE id = ? AND used_at IS NULL')
      .bind(row.id).run();
    if (marked.meta.changes !== 1) throw invalid();
    await env.DB.prepare('DELETE FROM social_login_codes WHERE expires_at < ?').bind(new Date().toISOString()).run();
    const user = await env.DB.prepare('SELECT * FROM users WHERE id = ?').bind(row.user_id).first();
    if (!user || Number(user.is_active) !== 1) throw invalid();
    const jwt = await issueToken(env, user, null);
    return json(corsHeaders, { success: true, token: jwt, customer_id: user.id, user: publicUser(user) });
  }

  return null;
}
